import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { BoxGeometry, Group, Mesh, MeshStandardMaterial, Box3 } from 'three';
import { GLTFExporter } from 'three/addons/exporters/GLTFExporter.js';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

globalThis.FileReader ??= class {
  readAsArrayBuffer(blob) { blob.arrayBuffer().then(result => { this.result = result; this.onloadend?.(); }); }
};
// Meters in GLB; centimeters in the manifest. Interior: x=0..6, z=0..5, y=0..2.8.
const room = new Group();
room.name = 'Empty room · 600 × 500 × 280 cm interior';
const plaster = new MeshStandardMaterial({ color: '#ddd2c0', roughness: 0.95 });
const floor = new MeshStandardMaterial({ color: '#af9571', roughness: 0.82 });
const trim = new MeshStandardMaterial({ color: '#eee5d6', roughness: 0.8 });
function box(name, size, center, material) {
  const mesh = new Mesh(new BoxGeometry(...size), material);
  mesh.name = name; mesh.position.set(...center); room.add(mesh);
}
box('Floor', [6.24, .12, 5.24], [3, -.06, 2.5], floor);
box('North wall', [6.24, 2.8, .12], [3, 1.4, -.06], plaster);
box('West wall', [.12, 2.8, 5], [-.06, 1.4, 2.5], plaster);
box('East wall', [.12, 2.8, 5], [6.06, 1.4, 2.5], plaster);
box('South wall left', [2.62, 2.8, .12], [1.19, 1.4, 5.06], plaster);
box('South wall right', [2.62, 2.8, .12], [4.81, 1.4, 5.06], plaster);
box('Door lintel', [1, .6, .12], [3, 2.5, 5.06], plaster);
box('Ceiling', [6.24, .12, 5.24], [3, 2.86, 2.5], trim);
// Subtle floorboards give scale without substituting for the 5 cm placement overlay.
for (let x = .25; x < 6; x += .25) box('Floorboard seam', [.003, .001, 5], [x, .0005, 2.5], trim);
const binary = await new GLTFExporter().parseAsync(room, { binary: true });
const parsed = await new GLTFLoader().parseAsync(binary, '');
const bounds = name => new Box3().setFromObject(parsed.scene.getObjectByName(name.replaceAll(' ', '_')));
assert.ok(Math.abs(bounds('Floor').max.y) < 1e-6);
assert.ok(Math.abs(bounds('North wall').max.z) < 1e-6);
assert.ok(Math.abs(bounds('West wall').max.x) < 1e-6);
assert.ok(Math.abs(bounds('East wall').min.x - 6) < 1e-6);
assert.ok(Math.abs(bounds('Ceiling').min.y - 2.8) < 1e-6);
assert.ok(Math.abs(bounds('South wall left').max.x - 2.5) < 1e-6);
assert.ok(Math.abs(bounds('South wall right').min.x - 3.5) < 1e-6);
const dir = new URL('../../shared/rooms/empty-room/', import.meta.url);
await mkdir(dir, { recursive: true });
await writeFile(new URL('room.glb', dir), Buffer.from(binary));
const manifest = {
  room: { roomId: 'empty-room', revision: 1, widthCm: 600, depthCm: 500, heightCm: 280,
    scan: { geometryRevision: 'empty-room-v1', visualFormat: 'glb',
      calibration: { status: 'synthetic_demo', note: 'Authored test mesh with exact 600 × 500 × 280 cm interior; not a measured scan. Doorway is 100 × 220 cm; navigation remains inside the room.' },
      visualUrl: '/rooms/empty-room/room.glb', surfaceUrl: '/rooms/empty-room/room.glb',
      positionCm: [0,0,0], rotationDeg: [0,0,0], scale: 1,
      defaultCamera: { kind: 'firstPerson', xCm: 300, yCm: 160, zCm: 430, yawRad: 0, pitchRad: -.16, fovDeg: 65 },
      attribution: { title: 'Empty room', author: 'FRIDAY', url: '/rooms/empty-room/manifest.json', license: 'Project fixture', licenseUrl: '/rooms/empty-room/license.txt' }
    } }, spatialFile: 'spatial.json'
};
await writeFile(new URL('manifest.json', dir), JSON.stringify(manifest, null, 2)+'\n');
await writeFile(new URL('spatial.json', dir), JSON.stringify({freeAreas:[{minXcm:0,maxXcm:600,minZcm:0,maxZcm:500}],obstacles:[]}, null, 2)+'\n');
await writeFile(new URL('license.txt', dir), 'Authored for FRIDAY. Generated by frontend/scripts/generate-empty-room.mjs; no third-party model content.\n');
console.log(`Empty room GLB: ${binary.byteLength} bytes. Roundtrip floor, wall, ceiling and doorway bounds passed.`);
